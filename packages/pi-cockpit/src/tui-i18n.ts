export interface CockpitTuiLocaleOptions extends SystemSettingsLocaleOptions {
	locale?: string | null;
	detectSystemLocale?: (options?: SystemSettingsLocaleOptions) => SupportedSettingsLocale;
}

export interface CockpitLocaleEventSource {
	on(event: string, handler: (payload: unknown) => void): void | (() => void);
}

export class CockpitTuiLocale {
	private readonly translator: SettingsTranslator;
	private readonly listeners = new Set<(locale: SupportedSettingsLocale) => void>();

	constructor(options: CockpitTuiLocaleOptions = {}) {
		const systemOptions: SystemSettingsLocaleOptions = {
			...(options.environment === undefined ? {} : { environment: options.environment }),
			...(options.resolvedLocale === undefined ? {} : { resolvedLocale: options.resolvedLocale }),
		};
		const locale = options.locale === undefined || options.locale?.trim().toLowerCase() === "auto"
			? (options.detectSystemLocale ?? detectSystemSettingsLocale)(systemOptions)
			: resolveSettingsLocale(options.locale, systemOptions);
		this.translator = createSettingsTranslator({ locale, catalogs: COCKPIT_TUI_CATALOGS });
	}

	get locale(): SupportedSettingsLocale {
		return this.translator.locale;
	}

	setLocale(locale: string | null | undefined): SupportedSettingsLocale {
		const previous = this.translator.locale;
		const next = this.translator.setLocale(locale);
		if (next === previous) return next;
		for (const listener of [...this.listeners]) {
			try { listener(next); } catch { /* locale observers must not break the caller */ }
		}
		return next;
	}

	t(key: string, params?: TranslationParams): string {
		return this.translator.t(key, params);
	}

	subscribe(listener: (locale: SupportedSettingsLocale) => void): () => void {
		this.listeners.add(listener);
		return () => this.listeners.delete(listener);
	}

	applyEvent(payload: unknown): boolean {
		if (!isSettingsLocaleEvent(payload)) return false;
		this.setLocale(payload.locale);
		return true;
	}
}

function isSettingsLocaleEvent(payload: unknown): payload is SettingsLocaleEventV1 {
	if (!payload || typeof payload !== "object" || Array.isArray(payload)) return false;
	const event = payload as Partial<SettingsLocaleEventV1>;
	return event.version === SETTINGS_PROTOCOL_VERSION
		&& (event.locale === "en" || event.locale === "zh-CN")
		&& typeof event.generation === "string"
		&& event.generation.trim().length > 0;
}

export const cockpitTuiLocale = new CockpitTuiLocale();

export function tuiT(key: string, params?: TranslationParams): string {
	return cockpitTuiLocale.t(key, params);
}

export function tuiStatus(status: string): string {
	const normalized = status.trim().toLowerCase().replaceAll("_", "-").replaceAll(" ", "-");
	const key = STATUS_KEYS[normalized];
	return key ? tuiT(key) : status;
}

export function bindCockpitTuiLocale(
	events: CockpitLocaleEventSource,
	runtime: CockpitTuiLocale = cockpitTuiLocale,
): () => void {
	const result = events.on(SETTINGS_LOCALE_EVENT, (payload) => runtime.applyEvent(payload));
	return typeof result === "function" ? result : () => {};
}

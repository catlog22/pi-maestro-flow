#!/usr/bin/env node
/**
 * Refresh the checked-in ACP agent registry snapshot.
 *
 * Run explicitly — never as part of a build, a test, or a dispatch. The
 * snapshot pins which package version each agent launches, so refreshing it
 * changes what every registration that names an agent will run. That belongs in
 * a reviewed commit, not in whatever the network answered during a run.
 *
 * Usage: node scripts/refresh-acp-registry.mjs [--check]
 *   --check  exit non-zero when the snapshot is stale, writing nothing
 *
 * `--check` is for a human deciding whether to refresh; it is deliberately not
 * wired into any gate. Upstream moves whenever any listed agent publishes, so a
 * gate on it would fail builds that changed nothing — which is the opposite of
 * pinning.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const SOURCE = "https://cdn.agentclientprotocol.com/registry/v1/latest/registry.json";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "backends", "acp-registry-snapshot.ts");

/**
 * Reduce one upstream entry to the launch facts this product can act on.
 *
 * Archive URLs, checksums and platform targets are dropped: nothing here
 * downloads or extracts anything, so keeping them would invite a reader to
 * think an operator does not have to install a binary agent themselves.
 *
 * @param agent - one upstream registry entry.
 * @returns the trimmed entry, or undefined when it declares no usable launch.
 */
async function trim(agent) {
  const dist = agent.distribution ?? {};
  const base = { id: agent.id, name: agent.name, version: agent.version };
  if (dist.npx?.package) {
    return {
      ...base,
      launch: {
        kind: "npx",
        command: "npx",
        args: ["-y", dist.npx.package, ...(dist.npx.args ?? [])],
        bins: await npmBinNames(dist.npx.package),
        runnerArgs: dist.npx.args ?? [],
      },
    };
  }
  if (dist.uvx?.package) {
    // No local candidates: PyPI does not publish console-script names in the
    // metadata this refresh reads, and guessing one would have this product run
    // whatever answers to that name on PATH.
    return { ...base, launch: { kind: "uvx", command: "uvx", args: [dist.uvx.package, ...(dist.uvx.args ?? [])], bins: [], runnerArgs: dist.uvx.args ?? [] } };
  }
  if (dist.binary) {
    // Kept per target rather than collapsed: the arguments genuinely differ by
    // platform for at least one agent (antigravity-acp passes `--uid=` on Linux
    // only), and a snapshot generated on one machine is consumed on every other.
    const argsByTarget = {};
    for (const [target, spec] of Object.entries(dist.binary)) argsByTarget[target] = spec.args ?? [];
    return { ...base, launch: { kind: "binary", argsByTarget } };
  }
  return undefined;
}

/**
 * The executable names an npm package installs, from the package's own manifest.
 *
 * Read rather than derived: the unscoped package name is not the command name
 * often enough to matter — `@google/gemini-cli` installs `gemini` and
 * `@qwen-code/qwen-code` installs `qwen`. A guess that misses costs only a
 * fallback to npx, but a guess that *hits* an unrelated program of the same
 * name would have this product launch it.
 *
 * @param spec - package specifier, optionally version-pinned.
 * @returns declared bin names, empty when the manifest declares none.
 */
async function npmBinNames(spec) {
  const at = spec.lastIndexOf("@");
  const name = at > 0 ? spec.slice(0, at) : spec;
  const manifest = await fetch(`https://registry.npmjs.org/${encodeURIComponent(name)}/latest`);
  if (!manifest.ok) return [];
  const bin = (await manifest.json()).bin;
  if (typeof bin === "string") return [name.split("/").pop()];
  return bin && typeof bin === "object" ? Object.keys(bin).sort() : [];
}

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${SOURCE} answered ${response.status}`);
const upstream = await response.json();
const agents = (await Promise.all((upstream.agents ?? []).map(trim))).filter(Boolean).sort((a, b) => a.id.localeCompare(b.id));
if (agents.length === 0) throw new Error("upstream registry listed no usable agents; refusing to write an empty snapshot");

const rendered = `/**
 * Launch metadata for the agents in the ACP registry, as of the last explicit
 * refresh.
 *
 * Generated by \`scripts/refresh-acp-registry.mjs\`; do not edit by hand. Pinned
 * on purpose: the versions below are what a registration naming an agent will
 * run, so they change in a reviewed commit rather than from whatever the
 * network answers during a dispatch. Nothing reads the network at run time.
 *
 * @see ${SOURCE}
 */

/**
 * An agent distributed through a package runner.
 *
 * \`command\` plus \`args\` launches it with no prior install. \`bins\` names the
 * executables the package installs, so a registration can prefer an already
 * installed copy: it starts immediately, where the runner re-resolves the
 * package and may download it first.
 */
export interface AcpRegistryRunnerLaunch {
  kind: "npx" | "uvx";
  command: string;
  args: readonly string[];
  /**
   * Read from the package manifest, never derived from its name — \`@google/gemini-cli\`
   * installs \`gemini\`. Empty means no local candidate is known, not that none
   * exists: uvx packages do not publish their script names where the refresh reads.
   */
  bins: readonly string[];
  /** Arguments that follow the executable when a local copy is used instead. */
  runnerArgs: readonly string[];
}

/**
 * An agent shipped as a platform executable.
 *
 * Nothing here downloads or extracts it, so the operator names the executable
 * and only the arguments come from the registry. Kept per target because they
 * genuinely differ by platform for at least one agent.
 */
export interface AcpRegistryBinaryLaunch {
  kind: "binary";
  /** Keyed \`<platform>-<arch>\`, e.g. \`darwin-aarch64\`, exactly as upstream states them. */
  argsByTarget: Readonly<Record<string, readonly string[]>>;
}

/** How an agent is launched, once an operator has whatever it needs installed. */
export type AcpRegistryLaunch = AcpRegistryRunnerLaunch | AcpRegistryBinaryLaunch;

/** One agent the registry lists, reduced to what a registration needs. */
export interface AcpRegistryAgent {
  id: string;
  name: string;
  version: string;
  launch: AcpRegistryLaunch;
}

/** Upstream registry document this snapshot was taken from. */
export const ACP_REGISTRY_SOURCE = ${JSON.stringify(SOURCE)};

/** Upstream registry schema version at the time of the refresh. */
export const ACP_REGISTRY_VERSION = ${JSON.stringify(upstream.version ?? "unknown")};

/** Every listed agent, by ascending id. */
export const ACP_REGISTRY_AGENTS: readonly AcpRegistryAgent[] = ${JSON.stringify(agents, null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf-8");
  if (current === rendered) {
    console.log(`acp registry snapshot is current (${agents.length} agents)`);
    process.exit(0);
  }
  console.error(`acp registry snapshot is stale; run: node scripts/refresh-acp-registry.mjs`);
  process.exit(1);
}

writeFileSync(OUT, rendered);
const kinds = agents.reduce((seen, a) => ({ ...seen, [a.launch.kind]: (seen[a.launch.kind] ?? 0) + 1 }), {});
console.log(`wrote ${agents.length} agents (${Object.entries(kinds).map(([k, n]) => `${k}=${n}`).join(", ")}) to ${OUT}`);
